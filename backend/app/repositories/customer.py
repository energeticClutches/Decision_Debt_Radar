"""Customer-evidence persistence (Day 5): classifications, insights and the customer evidence items of a decision."""

from __future__ import annotations

import uuid
from collections.abc import Iterable, Sequence

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.db.models import CustomerInsight, Evidence, LlmClassification


# ---------------------------------------------------------------- classifications (insert-only)
def cached_classifications(session: Session, text_hashes: Sequence[str], taxonomy_id: str, prompt_version: str,
                           model: str) -> dict[str, LlmClassification]:
    """text_sha256 -> the earliest stored classification with the same taxonomy, prompt version and model. The cache may be read
    across decisions, but only with the same taxonomy version (D5 section 4)."""
    out: dict[str, LlmClassification] = {}
    hashes = list(text_hashes)
    for i in range(0, len(hashes), 5000):
        rows = session.scalars(select(LlmClassification).where(
            LlmClassification.text_sha256.in_(hashes[i:i + 5000]), LlmClassification.taxonomy_version == taxonomy_id,
            LlmClassification.prompt_version == prompt_version, LlmClassification.model == model)
            .order_by(LlmClassification.created_at, LlmClassification.id))
        for row in rows:
            out.setdefault(row.text_sha256, row)
    return out


def existing_feedback_ids(session: Session, decision_id: uuid.UUID, taxonomy_id: str, prompt_version: str, model: str) -> set[int]:
    return set(session.scalars(select(LlmClassification.feedback_id).where(
        LlmClassification.decision_id == decision_id, LlmClassification.taxonomy_version == taxonomy_id,
        LlmClassification.prompt_version == prompt_version, LlmClassification.model == model)))


def add_classifications(session: Session, rows: Iterable[LlmClassification]) -> int:
    batch = list(rows)
    session.add_all(batch)
    session.flush()
    return len(batch)


def classification_counts(session: Session, decision_id: uuid.UUID, taxonomy_id: str) -> dict:
    """Counts of the stored classifications of a decision under one taxonomy version: total, per relevance and per theme."""
    rows = session.execute(
        select(LlmClassification.theme, LlmClassification.relevance, func.count())
        .where(LlmClassification.decision_id == decision_id, LlmClassification.taxonomy_version == taxonomy_id)
        .group_by(LlmClassification.theme, LlmClassification.relevance)).all()
    total = sum(n for _, _, n in rows)
    by_relevance: dict[str, int] = {}
    by_theme: dict[str, dict[str, int]] = {}
    for theme, relevance, n in rows:
        by_relevance[relevance] = by_relevance.get(relevance, 0) + n
        by_theme.setdefault(theme or "(none)", {})[relevance] = n
    return {"taxonomy_version": taxonomy_id, "total": total, "by_relevance": dict(sorted(by_relevance.items())),
            "by_theme": {k: dict(sorted(v.items())) for k, v in sorted(by_theme.items())}}


def classification_taxonomies(session: Session, decision_id: uuid.UUID) -> list[str]:
    return sorted(set(session.scalars(select(LlmClassification.taxonomy_version).where(LlmClassification.decision_id == decision_id))))


# ---------------------------------------------------------------- insights and customer evidence
def add_insight(session: Session, **fields) -> CustomerInsight:
    row = CustomerInsight(**fields)
    session.add(row)
    session.flush()
    session.refresh(row)
    return row


def evidence_by_identity(session: Session, decision_id: uuid.UUID, identity: str) -> list[Evidence]:
    """Every evidence row of the decision with this identity, whatever its status (a rejected identity is never re-proposed)."""
    return list(session.scalars(select(Evidence).where(Evidence.decision_id == decision_id, Evidence.analysis_identity == identity)
                                .order_by(Evidence.created_at, Evidence.id).execution_options(populate_existing=True)))


def customer_items(session: Session, decision_id: uuid.UUID) -> list[tuple[Evidence, CustomerInsight | None]]:
    """Customer evidence generated by the pipeline (created_by agent), with its insight, oldest first."""
    stmt = (select(Evidence, CustomerInsight).outerjoin(CustomerInsight, CustomerInsight.id == Evidence.insight_id)
            .where(Evidence.decision_id == decision_id, Evidence.evidence_type == "customer", Evidence.created_by == "agent")
            .order_by(Evidence.created_at, Evidence.id).execution_options(populate_existing=True))
    return [(e, i) for e, i in session.execute(stmt).all()]


def live_items_for_theme(session: Session, decision_id: uuid.UUID, theme: str, *, except_identity: str) -> list[Evidence]:
    """Active or proposed customer items of this theme with another identity (they are superseded by a new identity)."""
    stmt = (select(Evidence).join(CustomerInsight, CustomerInsight.id == Evidence.insight_id)
            .where(Evidence.decision_id == decision_id, Evidence.evidence_type == "customer", Evidence.created_by == "agent",
                   Evidence.status.in_(("active", "proposed")), Evidence.analysis_identity.is_not(None),
                   Evidence.analysis_identity != except_identity, CustomerInsight.theme == theme)
            .order_by(Evidence.id).execution_options(populate_existing=True))
    return list(session.scalars(stmt))


def get_evidence_with_insight(session: Session, evidence_id: uuid.UUID) -> tuple[Evidence, CustomerInsight | None] | None:
    row = session.execute(select(Evidence, CustomerInsight).outerjoin(CustomerInsight, CustomerInsight.id == Evidence.insight_id)
                          .where(Evidence.id == evidence_id).execution_options(populate_existing=True)).first()
    return None if row is None else (row[0], row[1])
