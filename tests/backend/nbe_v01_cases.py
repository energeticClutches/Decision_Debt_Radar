"""Deterministic NBE fixture set and serializer used by the v0.1 preservation test (Day 4.1, T-GUARD-1 / B1).

`golden_nbe_v01.json` was generated by running `build_outputs()` against the NBE engine at the Day-3 baseline commit
f6209e9 (regenerate it only by exporting that commit's backend/ tree and running this module's __main__ with PYTHONPATH
pointing at it). The test compares the current engine, evaluated under nbe_params_v0.1, with that file.
"""

from __future__ import annotations

import json
import random
import sys
from dataclasses import asdict
from pathlib import Path

from ddi_factories import AS_OF, METRIC, METRIC_DS, PARAMS, facts, good_experiment, item, random_facts

from app.domain.ddi import assess, components_from_scores, score_components
from app.domain.facts import DqIssue, InsightFact
from app.domain.nbe import recommend

DIMS = dict(D1=0.55, D2=0.714, D3=0.60, D4=0.10, D5=0.65, D6=0.45, D7=0.30)
ALL_TYPES = frozenset({"behavioral", "customer", "experiment", "financial"})
GOLDEN = Path(__file__).with_name("golden_nbe_v01.json")


def _dump(recs) -> list[dict]:
    return [asdict(r) for r in recs]


def _insufficient_cases(rng: random.Random):
    for k in range(120):
        dtype = rng.choice(["product_feature_investment", "pricing_change", "process_or_ux_change"])
        n = rng.randint(0, 4)
        types = ["behavioral", "customer", "experiment", "financial", "market"]
        items = []
        for j in range(n):
            t = rng.choice(types)
            kw = dict(type=t, ds=rng.choice([None, METRIC_DS, "ds-a"]), grade=rng.choice("ABCD"))
            if t == "behavioral" and rng.random() < 0.5:
                kw["metric_id"] = METRIC
            items.append(item(f"i{j}", **kw))
        dq = []
        if rng.random() < 0.7:
            dq.append(DqIssue("q1", METRIC_DS, "critical", rng.choice(["open", "open", "accepted"]), affects_metric_id=METRIC))
        if rng.random() < 0.3:
            dq.append(DqIssue("q2", "ds-a", rng.choice(["warn", "critical"]), "open"))
        yield f"insufficient-{k}", facts(items, decision_type=dtype, dq=dq, metric_ds=rng.choice([METRIC_DS, None]))


def build_outputs(params=PARAMS, nbe=None) -> dict:
    if nbe is None:
        from ddi_factories import NBE as nbe          # noqa: N811
    out: dict = {}
    comps = components_from_scores("product_feature_investment", DIMS, 0.20, 0.30, params, d6_raw=0.45, types_present=ALL_TYPES,
                                   details={"D4": {"best_design": "holdout", "best_power_factor": 0.5}})
    out["worked-example"] = _dump(recommend(score_components(comps, params, AS_OF), None, params, nbe))
    items = [item("a", type="behavioral", metric_id=METRIC, ds=METRIC_DS), item("b", type="customer"), item("c", type="behavioral")]
    f = facts(items, decision_type="process_or_ux_change", dq=[DqIssue("q1", METRIC_DS, "critical", "open", affects_metric_id=METRIC)])
    out["onboarding-like"] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    f = facts([])
    out["empty"] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    f = facts([item(f"b{i}", type="behavioral", metric_id=METRIC) for i in range(3)])
    out["min-types-only"] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    f = facts([item("a", type="behavioral", metric_id=METRIC, ds="ds-a", tier=2), item("b", type="customer", ds="ds-b"),
               item("c", type="financial", ds="ds-b"), item("d", type="experiment", experiment_id="x1", ds="ds-c")],
              experiments=[good_experiment()], insights=[InsightFact("ins", 10)],
              dq=[DqIssue("q1", "ds-a", "warn", "open"), DqIssue("q2", "ds-b", "critical", "open")], metric_ds=METRIC_DS)
    out["per-source-dq"] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    rng = random.Random(2026)
    for k in range(150):
        f = random_facts(rng)
        out[f"random-{k}"] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    for name, f in _insufficient_cases(random.Random(41)):
        out[name] = _dump(recommend(assess(f, params, AS_OF), f, params, nbe))
    return json.loads(json.dumps(out, sort_keys=True, default=str))


if __name__ == "__main__":
    # run with the baseline backend on PYTHONPATH; the NBE parameters are the baseline's only (v0.1) file
    from app.core.params import load_nbe_params
    nbe_v01 = load_nbe_params("nbe_params_v0.1", ddi_params=PARAMS)
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else GOLDEN
    target.write_text(json.dumps(build_outputs(PARAMS, nbe_v01), indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    print("wrote", target)
