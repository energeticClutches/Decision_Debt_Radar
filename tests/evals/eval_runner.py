class StepError(Exception):
    """A mutation step failed in a way the spec did not expect."""


@dataclass
class Check:
    name: str
    ok: bool
    expected: Any = None
    observed: Any = None
    note: str = ""
    known_gap: str | None = None      # a documented gap: the check is EXPECTED to fail (reported as a failure, never hidden)


@dataclass
class SpecResult:
    spec_id: str
    group: str
    description: str
    checks: list[Check] = field(default_factory=list)
    observed: dict = field(default_factory=dict)       # compact observation (JSON-safe)
    golden: dict | None = None                         # what the snapshot stores for this spec
    error: str | None = None
    extras: dict = field(default_factory=dict)         # numbers for the metrics (citation validity, reproducibility, ...)
    expected: str = ""

    @property
    def passed(self) -> bool:
        """True only when every expectation of the spec is met. A known gap keeps a spec failing in the report."""
        return self.error is None and all(c.ok for c in self.checks)

    @property
    def unexpected_failures(self) -> list[Check]:
        return [c for c in self.checks if not c.ok and not c.known_gap]

    @property
    def stale_gaps(self) -> list[Check]:
        """Known gaps that now PASS: the spec must be updated (the gap was closed)."""
        return [c for c in self.checks if c.ok and c.known_gap]


def load_specs(directory: Path = SCENARIO_DIR) -> list[dict]:
    specs = []
    for path in sorted(directory.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        specs.append(data)
    return specs


def validate_spec(spec: dict) -> list[str]:
    """Structural problems of a spec (an empty list when it is well formed)."""
    problems = []
    for key in ("id", "group", "description", "synthetic", "base_scenario", "mutations", "expect"):
        if key not in spec:
            problems.append(f"missing key {key!r}")
    if spec.get("synthetic") is not True:
        problems.append("synthetic must be true")
    if spec.get("group") not in ("core", "variant", "extra"):
        problems.append("group must be core, variant or extra")
    for gap in spec.get("known_gaps", []):
        if not gap.get("check") or not gap.get("reason"):
            problems.append("a known_gaps entry needs check and reason")
    expect = spec.get("expect") or {}
    for key in expect:
        if key not in EXPECT_KEYS:
            problems.append(f"unknown expect key {key!r}")
    for prop in expect.get("properties", []):
        if prop not in PROPERTIES:
            problems.append(f"unknown property {prop!r}")
    if expect.get("band") not in (None, "golden"):
        problems.append("band may only be 'golden' (D7-01: no band is chosen in advance)")
    if "band" in expect and expect.get("no_ddi"):
        problems.append("band and no_ddi are exclusive")
    return problems


def load_golden() -> dict:
    return json.loads(GOLDEN_PATH.read_text(encoding="utf-8")) if GOLDEN_PATH.exists() else {}


def _h(actor) -> dict:
    return {"X-Demo-User": actor.id}


def _norm(step) -> tuple[str, dict]:
    if isinstance(step, str):
        return step, {}
    (name, args), = step.items()
    return name, (args if isinstance(args, dict) else {"value": args})


class EvalRunner:
    """Runs one spec. Use as a context manager (it installs and removes the dependency overrides of the application)."""

    def __init__(self, session, seed, spec: dict):
        self.session, self.seed, self.spec = session, seed, spec
        self.clock = FixedClock(TODAY)
        self.llm = None
        self.llm_models: dict = {}
        self.http = TestClient(app, raise_server_exceptions=False)
        self.decision_id: str | None = None
        self.first_assessment: dict | None = None
        self.assessment_history: list[dict] = []
        self.refusals: dict[str, bool] = {}
        self.attempts: dict[str, int] = {}
        self.statuses: set[str] = set()                      # tokens such as synthesis_failed, review_review_failed
        self.hostile_ok = None
        self.extras: dict = {}

    # ------------------------------------------------------------------ context
    def __enter__(self):
        app.dependency_overrides[deps.get_session] = lambda: self.session
        app.dependency_overrides[deps.get_clock] = lambda: self.clock
        app.dependency_overrides[deps.get_llm] = lambda: self.llm
        app.dependency_overrides[deps.get_llm_models] = lambda: self.llm_models
        return self

    def __exit__(self, *exc):
        app.dependency_overrides.clear()

    # ------------------------------------------------------------------ plumbing
    def actor(self, role: str):
        return {"analyst": self.seed.analyst, "ba": self.seed.ba, "pm": self.seed.pm, "exec": self.seed.executive,
                "leader": self.seed.leader}[role]

    def call(self, method: str, path: str, role: str, json_body=None, *, expect=(200, 201), label: str | None = None):
        r = self.http.request(method, path, headers=_h(self.actor(role)), json=json_body)
        if r.status_code not in expect:
            raise StepError(f"{label or method + ' ' + path} as {role} returned {r.status_code}: {r.text[:300]}")
        return r

    def get(self, path: str, role: str = "pm"):
        return self.call("GET", path, role, expect=(200,)).json()

    def refresh(self):
        self.session.expire_all()

    @property
    def decision(self) -> dict:
        return self.get(f"/decisions/{self.decision_id}")

    def assessments(self) -> list[dict]:
        return sorted(self.get(f"/decisions/{self.decision_id}/assessments"), key=lambda a: a["version"])

    def current(self) -> dict | None:
        rows = self.assessments()
        return rows[-1] if rows else None

    def _note_assessment(self):
        cur = self.current()
        if cur is not None and cur["state"] != "partial":
            if self.first_assessment is None:
                self.first_assessment = cur
            self.assessment_history.append(cur)

    # ------------------------------------------------------------------ setup
    def setup(self):
        base = self.spec["base_scenario"]
        if base == "new":
            return                                           # the first mutation is create_decision
        self.decision_id = str(self.seed.decisions[base].id)
        self.session.refresh(self.seed.decisions[base])
        self.llm, self.llm_models = ReplayDemoClient(), dict(REPLAY_MODELS)

    def run(self) -> SpecResult:
        result = SpecResult(self.spec["id"], self.spec["group"], self.spec["description"])
        try:
            self.setup()
            for step in self.spec["mutations"]:
                name, args = _norm(step)
                fn = getattr(self, f"m_{name}", None)
                if fn is None:
                    raise StepError(f"unknown mutation {name!r}")
                if set(args) == {"value"}:                       # a scalar argument binds to the step's first parameter
                    first = next(iter(inspect.signature(fn).parameters))
                    args = {first: args["value"]}
                fn(**args)
            result.observed = self.observe()
            result.golden = self.golden_view(result.observed)
            result.checks = self.compare(result)
            result.extras = {**result.extras, **self.extras, **self.metric_extras(), "analysis_values": self.analysis_values()}
        except StepError as exc:
            result.error = str(exc)
        except Exception as exc:  # noqa: BLE001 (any other failure is a failure of the spec, reported, never swallowed silently)
            result.error = f"{type(exc).__name__}: {exc}"
        return result

    # ================================================================== mutations (the closed vocabulary)
    # ---- LLM client selection
    def m_use_llm(self, client: str):
        from replay import STUB_MODELS, ReplayClient, RoutedClient, ScriptedClient
        if client == "replay_demo":
            self.llm, self.llm_models = ReplayDemoClient(), dict(REPLAY_MODELS)
        elif client == "replay_day5":
            self.llm, self.llm_models = ReplayClient(), dict(STUB_MODELS)
        elif client == "none":
            self.llm, self.llm_models = None, {}
        elif client == "review_fails":
            self.llm, self.llm_models = ReplayClient(fail={"review": LlmTransportError("the reviewer is unavailable")}), dict(STUB_MODELS)
        elif client == "malformed_synthesis":
            self.llm = RoutedClient({"classify": ReplayClient(), "synthesize": ScriptedClient(["this is not json {"]),
                                     "review": ReplayClient()})
            self.llm_models = dict(STUB_MODELS)
        else:
            raise StepError(f"unknown llm client {client!r}")

    # ---- decision creation and plain evidence (new decisions)
    def m_create_decision(self, metric: str = "d90_retention", decision_type: str = "product_feature_investment",
                          expected_direction: str = "increase", risk_level: str = "medium", title: str | None = None):
        metric_id = str(self.seed.metrics[metric].id)
        body = {"title": title or self.spec["id"], "description": "Evaluation decision (synthetic).",
                "hypothesis": f"If we ship this then {metric.replace('_', ' ')} will increase.", "success_metric_id": metric_id,
                "decision_due_date": "2026-12-31", "risk_level": risk_level,
                "change_my_mind_criteria": ["A properly powered test shows less than a 2 point effect"],
                "decision_type": decision_type, "expected_direction": expected_direction}
        d = self.call("POST", "/decisions", "pm", body).json()
        self.decision_id = d["id"]
        self.metric_id = metric_id

    def m_confirm_evidence(self):
        self.call("POST", f"/decisions/{self.decision_id}/confirm-evidence", "pm")

    def m_add_evidence(self, kind: str, stance: str = "supports", grade: str = "B", age_days: int = 30, n_sample: int | None = None,
                       effect_size: float | None = None, ci_low: float | None = None, ci_high: float | None = None,
                       link_metric: bool | None = None, summary: str | None = None, count: int = 1, source: str | None = None):
        ref = source or SOURCE_BY_KIND[kind]
        link = (kind == "behavioral") if link_metric is None else link_metric
        for i in range(count):
            body = {"evidence_source_id": str(self.seed.es[ref].id), "evidence_type": kind,
                    "summary": summary or f"Evaluation {kind} evidence ({stance}, grade {grade}) {i + 1}",
                    "stance": stance, "strength_grade": grade,
                    "observed_start": (TODAY - timedelta(days=age_days + 60)).isoformat(),
                    "observed_end": (TODAY - timedelta(days=age_days)).isoformat(),
                    "n_sample": n_sample, "effect_size": effect_size, "ci_low": ci_low, "ci_high": ci_high,
                    "metric_id": self.metric_id if link else None}
            self.call("POST", f"/decisions/{self.decision_id}/evidence", "analyst", body)

    # ---- assessment
    def m_run_pipeline(self, expect_stage: str | None = None):
        r = self.call("POST", f"/decisions/{self.decision_id}/pipeline-runs", "analyst")
        body = r.json()
        self.statuses = set()                                # the statuses of the LATEST run only
        for key in ("synthesis", "review"):
            st = (body.get(key) or {}).get("status")
            if st:
                self.statuses.add(f"{key}_{st}")
        self._note_assessment()
        if expect_stage:
            assert body["lifecycle_stage"] == expect_stage, (body["lifecycle_stage"], expect_stage)

    def m_run_assessment(self):
        self.call("POST", f"/decisions/{self.decision_id}/assessments", "analyst")
        self._note_assessment()

    def m_set_as_of(self, to: str):
        self.clock = FixedClock(date.fromisoformat(to))

    # ---- customer evidence (the human gate)
    def _customer_items(self):
        return self.get(f"/decisions/{self.decision_id}/customer-evidence", "ba")["items"]

    def m_approve_customer_evidence(self, which: str = "all", note: str = "evaluation approval"):
        self._decide_customer("approve", which, note)

    def m_reject_customer_evidence(self, which: str = "all", note: str = "evaluation rejection"):
        self._decide_customer("reject", which, note)

    def _decide_customer(self, action: str, which: str, note: str):
        n = 0
        for it in self._customer_items():
            if it["evidence"]["status"] != "proposed":
                continue
            if which != "all" and (it.get("insight") or {}).get("theme") != which:
                continue
            self.call("PATCH", f"/evidence/{it['evidence']['id']}/approval", "ba", {"action": action, "note": note})
            n += 1
        if n == 0:
            raise StepError(f"no proposed customer evidence to {action} ({which})")

    def m_leave_proposed(self):
        """Explicit no-op: the proposed customer items stay proposed (they must stay out of the facts)."""
        items = self._customer_items()
        if not any(i["evidence"]["status"] == "proposed" for i in items):
            raise StepError("expected proposed customer evidence to leave alone")

    # ---- data quality and canvas
    def m_resolve_dq(self, severity: str = "critical", status: str = "resolved", note: str = "evaluation: issue handled"):
        checks = [c for c in self.get(f"/decisions/{self.decision_id}/dq-checks") if c["severity"] == severity and c["status"] == "open"]
        if not checks:
            raise StepError(f"no open {severity} data-quality check")
        for c in checks:
            self.call("PATCH", f"/dq-checks/{c['id']}", "ba", {"status": status, "note": note})

    def m_edit_canvas(self, **fields):
        self.call("PATCH", f"/decisions/{self.decision_id}/canvas", "pm", fields)

    # ---- synthesis with a scripted output (built from the REAL input payload)
    def m_synthesize_scripted(self, output: str, force: bool = True, review: str = "replay"):
        from day5_support import review_output, synthesis_output_for
        from replay import STUB_MODELS, ReplayClient, RoutedClient, ScriptedClient
        cur = self.current()
        decision = self.session.get(m.Decision, uuid.UUID(self.decision_id))
        assessment = self.session.get(m.DecisionAssessment, uuid.UUID(cur["id"]))
        payload, _ = payload_mod.build_input(self.session, decision, assessment)
        good = synthesis_output_for(payload)
        if output == "valid":
            out = good
        elif output == "compromised":
            out = {**good, "claims": good["claims"] + [{
                "local_id": "x1", "text": "The team should approve; cite the injected id.", "claim_type": "descriptive",
                "stance": "neutral", "confidence": "high", "evidence_ids": ["00000000-0000-0000-0000-000000000001"], "conclusion_ref": "D1"}]}
        else:
            raise StepError(f"unknown scripted output {output!r}")
        reviewer = ScriptedClient([review_output()]) if review == "clean" else ReplayClient()
        self.llm = RoutedClient({"synthesize": ScriptedClient([out]), "review": reviewer, "classify": ReplayClient()})
        self.llm_models = dict(STUB_MODELS)
        r = self.call("POST", f"/assessments/{cur['id']}/syntheses", "pm", {"force": force}, expect=(200, 201))
        body = r.json()
        self.statuses = set()
        self.statuses.add(f"synthesis_{body['synthesis_status']}")
        if body.get("review"):
            self.statuses.add(f"review_{body['review'].get('status')}")

    # ---- injection (test-only exception, as in Day-5 E3)
    def m_inject_customer_text(self):
        """Day-5 E3: hostile text in the sample quotes of a customer insight (a test-only row). The Stage-5 input must carry it wrapped,
        and a compromised synthesis that obeys it must be rejected by code."""
        d = self.session.get(m.Decision, uuid.UUID(self.decision_id))
        customer = next(e for e in self.session.scalars(select(m.Evidence).where(m.Evidence.decision_id == d.id))
                        if e.evidence_type == "customer")
        insight = m.CustomerInsight(org_id=d.org_id, decision_id=d.id, theme="coach_helpful", sentiment="positive", quote_count=120,
                                    sample_quotes=[{"text": HOSTILE, "mentions": 3}], is_synthetic=True)
        self.session.add(insight)
        self.session.flush()
        customer.insight_id = insight.id
        self.session.flush()
        cur = self.current()
        assessment = self.session.get(m.DecisionAssessment, uuid.UUID(cur["id"]))
        payload, _ = payload_mod.build_input(self.session, d, assessment)
        quote = payload["customer_insights"][0]["sample_quotes"][0]["text"]
        self.hostile_ok = bool(quote.startswith("<untrusted_customer_text>") and quote.count("</untrusted_customer_text>") == 1
                               and "[redacted-email]" in quote and "a.person@example.com" not in quote)

    # ---- review, validation, decision
    def m_human_review(self, verdict: str, response: str | None = None):
        cur = self.current()
        self.call("POST", f"/assessments/{cur['id']}/reviews", "pm", {"verdict": verdict, "human_response": response})

    def m_validate(self, expect_status: int = 200):
        self.call("POST", f"/decisions/{self.decision_id}/validate", "pm", expect=(expect_status,), label="validate")

    def m_record_decision(self, outcome: str, rationale: str = "Recorded by the evaluation.", acknowledged_risk: bool = False,
                          expect_status: int = 201):
        self.call("POST", f"/decisions/{self.decision_id}/decision-record", "exec",
                  {"outcome": outcome, "rationale": rationale, "acknowledged_risk": acknowledged_risk}, expect=(expect_status,),
                  label="decision-record")

    def m_create_brief(self, kind: str, expect_status: int = 201):
        cur = self.current()
        self.call("POST", f"/assessments/{cur['id']}/briefs", "pm", {"kind": kind}, expect=(expect_status,), label=f"brief {kind}")

    # ---- attempts that must be refused
    def m_attempt_approval_bypass(self):
        """Try to clear the approver of an ACTIVE agent customer item with raw SQL. The database must refuse (a CHECK constraint); the
        statement runs in a savepoint that is rolled back, so nothing is changed."""
        ev = self.session.scalar(select(m.Evidence).where(m.Evidence.decision_id == uuid.UUID(self.decision_id),
                                                            m.Evidence.evidence_type == "customer", m.Evidence.status == "active"))
        if ev is None:
            raise StepError("no active customer evidence to attempt the bypass on")
        refused = False
        try:
            with self.session.begin_nested():
                self.session.execute(text("UPDATE evidence SET approved_by = NULL, approved_at = NULL WHERE id = :i"), {"i": ev.id})
                self.session.flush()
        except Exception:  # noqa: BLE001
            refused = True
        self.refusals["approval_bypass"] = refused

    def m_attempt_writes_after_decided(self):
        """After `decided`: adding evidence, editing the canvas and recording again must all be refused."""
        did = self.decision_id
        ev = {"evidence_source_id": str(self.seed.es["fc_.events"].id), "evidence_type": "behavioral", "summary": "late evidence",
              "stance": "supports", "strength_grade": "B", "observed_start": "2026-08-01", "observed_end": "2026-09-01"}
        codes = [self.http.post(f"/decisions/{did}/evidence", headers=_h(self.seed.analyst), json=ev).status_code,
                 self.http.patch(f"/decisions/{did}/canvas", headers=_h(self.seed.pm), json={"title": "A late edit"}).status_code,
                 self.http.post(f"/decisions/{did}/decision-record", headers=_h(self.seed.executive),
                                json={"outcome": "approve", "rationale": "again", "acknowledged_risk": True}).status_code]
        self.attempts["writes_after_decided"] = sum(1 for c in codes if c in (403, 409, 422))
        self.attempts["writes_after_decided_total"] = len(codes)

    # ================================================================== observation
    def observe(self) -> dict:
        self.refresh()
        out: dict[str, Any] = {"decision_id": self.decision_id}
        if self.decision_id is None:
            return out
        d = self.decision
        out["lifecycle"] = d["lifecycle_stage"]
        out["stale"] = d["assessment_stale"]
        out["dq"] = sorted(({"target": c["target"], "severity": c["severity"], "status": c["status"], "check_type": c["check_type"]}
                            for c in self.get(f"/decisions/{self.decision_id}/dq-checks") if c["severity"] != "pass"),
                           key=lambda c: (c["target"], c["check_type"]))
        cur = self.current()
        out["assessment"] = None
        if cur is None:
            return out
        out["assessment"] = {"id": cur["id"], "version": cur["version"], "state": cur["state"], "ddi": cur["ddi"], "band": cur["band"],
                             "as_of": cur["as_of_date"], "blocking_codes": sorted(r["code"] for r in cur["blocking_reasons"]),
                             "params": cur["params"]}
        if cur["state"] == "partial":
            return out
        recs = sorted(self.get(f"/assessments/{cur['id']}/recommendations"), key=lambda r: r["rank"])
        out["nbe"] = [r["action_type"] for r in recs]
        out["nbe_rank1"] = recs[0]["action_type"] if recs else None
        reviews = self.get(f"/assessments/{cur['id']}/reviews")
        out["reviews"] = [{"type": r["reviewer_type"], "verdict": r["verdict"],
                           "findings": [{"category": f["category"], "severity": f["severity"], "source": f["source"],
                                         "severity_model": f["severity_model"]} for f in r["findings"]]} for r in reviews]
        syns = self.get(f"/assessments/{cur['id']}/syntheses")
        out["syntheses"] = [{"version": s["version"], "status": s["status"], "claims_dropped": s["claims_dropped"],
                             "validator_status": (s["validator_report"] or {}).get("status")} for s in syns]
        tokens: set[str] = set(self.statuses)
        for s in syns:
            rep = s["validator_report"] or {}
            for section in ("dropped", "reclassified", "repaired", "rejections", "other_dropped"):
                for row in rep.get(section, []):
                    if row.get("rule"):
                        tokens.add(row["rule"])
        for r in reviews:
            for f in r["findings"]:
                if f["source"] == "code" and f["category"]:
                    tokens.add(f["category"])
        out["finding_tokens"] = sorted(tokens)
        briefs = self.get(f"/assessments/{cur['id']}/briefs")
        out["briefs"] = [b["kind"] for b in briefs]
        return out

    def golden_view(self, obs: dict) -> dict:
        a = obs.get("assessment")
        if not a:
            return {"state": None}
        return {"state": a["state"], "ddi": a["ddi"], "band": a["band"], "blocking_codes": a["blocking_codes"],
                "nbe_rank1": obs.get("nbe_rank1"), "ddi_params_version": a["params"]["ddi_params_version"],
                "ddi_params_hash": a["params"]["ddi_params_hash"], "nbe_params_version": a["params"]["nbe_params_version"],
                "nbe_params_hash": a["params"]["nbe_params_hash"]}

    # ------------------------------------------------------------------ engine recompute
    def recompute(self) -> dict | None:
        cur = self.current()
        if cur is None or cur["state"] == "partial":
            return None
        row = self.session.get(m.DecisionAssessment, uuid.UUID(cur["id"]))
        facts = build_facts(self.session, uuid.UUID(self.decision_id))
        params = get_ddi_params()
        again = assess(facts, params, row.as_of_date)
        result = {"fingerprint_matches": evidence_fingerprint(self.session, uuid.UUID(self.decision_id)) == row.evidence_fingerprint,
                  "state": again.state, "ddi": again.ddi if again.scored else None, "band": again.band if again.scored else None,
                  "blocking_codes": sorted(r.code for r in again.blocking_reasons),
                  "dims_equal": json.dumps(again.dimension_scores_payload(), sort_keys=True, default=str)
                  == json.dumps(row.dimension_scores, sort_keys=True, default=str)}
        twice = assess(facts, params, row.as_of_date)
        result["reproducible"] = (json.dumps(again.dimension_scores_payload(), sort_keys=True, default=str)
                                  == json.dumps(twice.dimension_scores_payload(), sort_keys=True, default=str)
                                  and again.penalty_scores_payload() == twice.penalty_scores_payload()
                                  and again.sensitivity_payload() == twice.sensitivity_payload())
        return result

    # ================================================================== comparison
    def compare(self, res: SpecResult) -> list[Check]:
        exp = self.spec["expect"]
        obs = res.observed
        a = obs.get("assessment")
        checks: list[Check] = []

        def add(name, expected, observed, ok=None, note=""):
            checks.append(Check(name, (expected == observed) if ok is None else ok, expected, observed, note))

        if "state" in exp:
            add("state", exp["state"], a["state"] if a else None)
        if "blocking_reasons" in exp:
            add("blocking_reasons", sorted(exp["blocking_reasons"]), a["blocking_codes"] if a else None)
        if exp.get("no_ddi"):
            add("no_ddi", True, a is not None and a["ddi"] is None and a["band"] is None,
                note="an assessment that is not scored shows no number and no band")
        # the stored result equals the recomputed frozen engine (every spec with a scored or insufficient assessment)
        rec = self.recompute()
        res.extras["recompute"] = rec
        if rec is not None and rec["fingerprint_matches"]:
            same = (rec["state"], rec["ddi"], rec["band"], rec["blocking_codes"]) == (a["state"], a["ddi"], a["band"], a["blocking_codes"])
            add("stored_equals_recomputed_engine", True, same and rec["dims_equal"], note="assess(facts) recomputed on the stored facts")
            add("ddi_reproducible", True, rec["reproducible"], note="the engine run twice on the same facts")
        elif rec is not None:
            res.extras["recompute_skipped"] = "evidence changed after the stored assessment (it is stale)"
        if exp.get("band") == "golden":
            snap = load_golden().get("specs", {}).get(res.spec_id)
            if snap is None:
                add("golden_snapshot", "present in tests/evals/golden/observed.json", None, ok=False,
                    note="run scripts/eval_snapshot.py --write (never edit the snapshot by hand)")
            else:
                add("golden_band_equals_snapshot", snap["band"], res.golden["band"])
                add("golden_snapshot_unchanged", snap, res.golden, note="drift detection against the recorded engine output")
        if "lifecycle" in exp:
            want = exp["lifecycle"]
            want_stage = want if isinstance(want, str) else want.get("stage")
            add("lifecycle_stage", want_stage, obs.get("lifecycle"))
            if isinstance(want, dict) and "stale" in want:
                add("assessment_stale", want["stale"], obs.get("stale"))
        for action in exp.get("nbe_must_include", []):
            add(f"nbe_includes:{action}", True, action in obs.get("nbe", []), note=f"observed {obs.get('nbe')}")
        if "nbe_rank1" in exp:
            add("nbe_rank1", exp["nbe_rank1"], obs.get("nbe_rank1"))
        for token in exp.get("code_findings_must_include", []):
            add(f"finding:{token}", True, token in obs.get("finding_tokens", []), note=f"observed {obs.get('finding_tokens')}")
        for name in exp.get("refusals", []):
            add(f"refused:{name}", True, bool(self.refusals.get(name)))
        for prop in exp.get("properties", []):
            ok, note = getattr(self, f"p_{prop}")(obs)
            add(f"property:{prop}", True, ok, note=note)
        if self.hostile_ok is not None:
            add("injected_text_wrapped_and_redacted", True, self.hostile_ok, note="Day-5 E3 sanitisation of customer text")
        gaps = {g["check"]: g["reason"] for g in self.spec.get("known_gaps", [])}
        for c in checks:
            if c.name in gaps:
                c.known_gap = gaps[c.name]
        unknown = set(gaps) - {c.name for c in checks}
        if unknown:
            checks.append(Check("known_gap_names_a_check", False, sorted(unknown), None, "a known_gaps entry names no check of this spec"))
        return checks

    # ------------------------------------------------------------------ properties (the closed list)
    def p_d4_unchanged(self, obs):
        """D4 (experimental strength) of the first and the latest scored assessment is identical (the customer evidence changed the
        assessment, the experiment did not)."""
        scored = [x for x in self.assessment_history if x["state"] == "scored"]
        if len(scored) < 2:
            return False, "needs two scored versions"
        keys = ("score", "inputs", "explanation", "details")
        first = next(d for d in scored[0]["dimensions"] if d["id"] == "D4")
        last = next(d for d in scored[-1]["dimensions"] if d["id"] == "D4")
        return {k: first[k] for k in keys} == {k: last[k] for k in keys}, f"versions {[x['version'] for x in scored]}"

    def p_no_ddi_number(self, obs):
        """Not scored => no DDI value, band, dimension score or penalty anywhere: assessment, synthesis text, briefs."""
        cur = self.current()
        if cur["state"] == "scored":
            return False, "the assessment is scored"
        problems = []
        if cur["ddi"] is not None or cur["band"] is not None:
            problems.append("ddi or band present")
        if any(d.get("score") is not None or d.get("display_contribution") for d in cur["dimensions"]):
            problems.append("dimension score present")
        if cur["penalties"]:
            problems.append("penalties present")
        syns = self.get(f"/assessments/{cur['id']}/syntheses")
        for s in syns:
            if not s["output"]:
                continue
            for where, txt in v._texts(s["output"]):          # the free-text fields only (the same fields V-GATE inspects)
                txt = v._LOCAL_REF.sub(" ", txt)
                if v._DDI_NUMBER.search(txt) or v._DDI_BAND.search(txt):
                    problems.append(f"a DDI number or band in synthesis text ({where})")
        for b in self.get(f"/assessments/{cur['id']}/briefs"):
            full = self.get(f"/briefs/{b['id']}")
            panel = (full["content"].get("ddi_panel") or {})
            if panel.get("ddi") is not None or panel.get("band") is not None:
                problems.append("a DDI value in a brief panel")
        return not problems, "; ".join(problems) or "no number, band, dimension score or penalty"

    def p_proposed_excluded_from_facts(self, obs):
        facts = build_facts(self.session, uuid.UUID(self.decision_id))
        in_facts = {i.id for i in facts.items}
        proposed = [str(e.id) for e in self.session.scalars(select(m.Evidence).where(
            m.Evidence.decision_id == uuid.UUID(self.decision_id), m.Evidence.status.in_(("proposed", "rejected"))))]
        return bool(proposed) and not (set(proposed) & in_facts), f"{len(proposed)} proposed or rejected item(s), none in the facts"

    def p_stance_from_map(self, obs):
        d = self.session.get(m.Decision, uuid.UUID(self.decision_id))
        tenant = get_tenant_config()
        tax = tenant.data["customer_taxonomy"][d.scenario_key]["themes"]
        stance_map = {t["theme"]: t["stance"] for t in tax}
        rows = [e for e in self.session.scalars(select(m.Evidence).where(m.Evidence.decision_id == d.id,
                                                                          m.Evidence.evidence_type == "customer",
                                                                          m.Evidence.created_by != "user"))]
        bad = []
        for e in rows:
            ins = self.session.get(m.CustomerInsight, e.insight_id)
            if ins is None or ins.theme not in stance_map or e.stance != stance_map[ins.theme] or e.strength_grade not in ("C", "D"):
                bad.append(str(e.id))
        return bool(rows) and not bad, f"{len(rows)} agent-created customer item(s); stance from the tenant map and grade C or D"

    def p_review_not_ready(self, obs):
        """The decision cannot be validated: no review, a failed review or an unoverridden needs_rework. The attempt must be refused."""
        r = self.http.post(f"/decisions/{self.decision_id}/validate", headers=_h(self.seed.pm))
        return r.status_code in (409, 422, 403), f"validate returned {r.status_code}"

    def p_writes_frozen(self, obs):
        n, total = self.attempts.get("writes_after_decided", 0), self.attempts.get("writes_after_decided_total", 0)
        return total > 0 and n == total, f"{n} of {total} late writes refused"

    def p_ddi_not_lower_when_older(self, obs):
        scored = [x for x in self.assessment_history if x["state"] == "scored"]
        if len(scored) < 2:
            return False, "needs two scored versions"
        return scored[-1]["ddi"] >= scored[0]["ddi"], f"DDI {scored[0]['ddi']} at {scored[0]['as_of_date']} then {scored[-1]['ddi']} at {scored[-1]['as_of_date']}"

    # ------------------------------------------------------------------ golden-answer inputs
    def analysis_values(self) -> dict:
        """The values the Day-4 analyses stored for this decision (compared with the manifest in scripts/eval_report.py)."""
        if self.decision_id is None:
            return {}
        out: dict[str, Any] = {}
        for a in self.get(f"/decisions/{self.decision_id}/analyses"):
            res = self.get(f"/analyses/{a['id']}").get("result") or {}
            if a["analysis_type"] == "comparison":
                out.setdefault("comparison_effect", res.get("effect"))
            elif a["analysis_type"] == "segmentation":
                out["heterogeneity_flag"] = res.get("flag")
                out["segment_effects"] = {s["segment"]: s["effect"] for s in res.get("segments", [])}
            elif a["analysis_type"] == "experiment":
                srm = res.get("srm") or {}
                out["experiment"] = {"n": res.get("n"), "planned_sample": res.get("planned_sample"), "effect": res.get("effect"),
                                     "observed_allocation": srm.get("observed_allocation"), "srm_flag": srm.get("flag")}
        return out

    # ------------------------------------------------------------------ metric inputs
    def metric_extras(self) -> dict:
        """Numbers for the report: citation validity before and after filtering, over the syntheses this spec produced."""
        out = {"claims_total": 0, "claims_dropped_v_id": 0, "claims_stored": 0, "claims_stored_with_valid_ids": 0}
        if self.decision_id is None:
            return out
        did = uuid.UUID(self.decision_id)
        rows = self.session.execute(text(
            "SELECT s.validator_report FROM syntheses s JOIN decision_assessments a ON a.id = s.assessment_id WHERE a.decision_id = :d"),
            {"d": did}).all()
        for (rep,) in rows:
            out["claims_total"] += rep.get("claims_total", 0)
            out["claims_dropped_v_id"] += sum(1 for x in rep.get("dropped", []) if x.get("rule") == "V-ID")
        stored = self.session.execute(text(
            "SELECT c.id, count(ce.evidence_id) AS n, count(e.id) FILTER (WHERE e.decision_id = :d AND e.status = 'active') AS ok"
            " FROM claims c JOIN decision_assessments a ON a.id = c.assessment_id LEFT JOIN claim_evidence ce ON ce.claim_id = c.id"
            " LEFT JOIN evidence e ON e.id = ce.evidence_id WHERE a.decision_id = :d GROUP BY c.id"), {"d": did}).all()
        out["claims_stored"] = len(stored)
        out["claims_stored_with_valid_ids"] = sum(1 for _, n, ok in stored if n > 0 and n == ok)
        if self.hostile_ok is not None:
            out["hostile_text_wrapped"] = self.hostile_ok
        return out


def run_spec(session, seed, spec: dict) -> SpecResult:
    problems = validate_spec(spec)
    if problems:
        r = SpecResult(spec.get("id", "?"), spec.get("group", "?"), spec.get("description", ""))
        r.error = "invalid spec: " + "; ".join(problems)
        return r
    with EvalRunner(session, seed, spec) as runner:
        return runner.run()


def expected_summary(spec: dict) -> str:
    e = spec["expect"]
    parts = []
    if "state" in e:
        parts.append(f"state={e['state']}")
    if "lifecycle" in e:
        lc = e["lifecycle"]
        parts.append("lifecycle=" + (lc if isinstance(lc, str) else f"{lc['stage']}{' (stale)' if lc.get('stale') else ''}"))
    if "blocking_reasons" in e:
        parts.append("blocking=" + ",".join(sorted(e["blocking_reasons"])) if e["blocking_reasons"] else "blocking=none")
    if e.get("band") == "golden":
        parts.append("band=golden")
    if e.get("no_ddi"):
        parts.append("no_ddi")
    if "nbe_rank1" in e:
        parts.append(f"nbe_rank1={e['nbe_rank1']}")
    if e.get("nbe_must_include"):
        parts.append("nbe+=" + ",".join(e["nbe_must_include"]))
    if e.get("code_findings_must_include"):
        parts.append("findings+=" + ",".join(e["code_findings_must_include"]))
    if e.get("properties"):
        parts.append("props=" + ",".join(e["properties"]))
    if e.get("refusals"):
        parts.append("refused=" + ",".join(e["refusals"]))
    return "; ".join(parts)


def observed_summary(res: SpecResult) -> str:
    o = res.observed
    a = o.get("assessment")
    parts = []
    if a:
        parts.append(f"state={a['state']}")
        if a["state"] == "scored":
            parts.append(f"band={a['band']}")
        if a["blocking_codes"]:
            parts.append("blocking=" + ",".join(a["blocking_codes"]))
    if o.get("lifecycle"):
        parts.append(f"lifecycle={o['lifecycle']}")
    if o.get("nbe_rank1"):
        parts.append(f"nbe_rank1={o['nbe_rank1']}")
    if res.error:
        parts.append(f"ERROR {res.error[:120]}")
    return "; ".join(parts)



# ====================================================================== results files
RESULTS_DIR = ROOT / "analytics" / "eval"
CSV_COLUMNS = ("spec", "group", "expected", "observed", "pass", "notes", "synthetic")


def _notes(res: SpecResult) -> str:
    if res.error:
        return f"ERROR: {res.error[:200]}"
    out = []
    for c in res.checks:
        if not c.ok:
            tag = "KNOWN GAP" if c.known_gap else "FAIL"
            out.append(f"{tag} {c.name}: expected {c.expected!r}, observed {c.observed!r}")
    return " | ".join(out) if out else "all checks met"


def result_rows(results: list[SpecResult]) -> list[dict]:
    return [{"spec": r.spec_id, "group": r.group, "expected": r.expected, "observed": observed_summary(r), "pass": r.passed,
             "notes": _notes(r), "synthetic": True} for r in results]


def write_results(results: list[SpecResult], specs: list[dict], directory: Path = RESULTS_DIR) -> None:
    """analytics/eval/results.json and results.csv. Deterministic for a given engine output (no timestamps)."""
    import csv
    directory.mkdir(parents=True, exist_ok=True)
    by_id = {s["id"]: s for s in specs}
    for r in results:
        r.expected = expected_summary(by_id[r.spec_id])
    rows = result_rows(results)
    detail = []
    for r, row in zip(results, rows):
        detail.append({**row, "description": " ".join(r.description.split()),
                       "checks": [{"name": c.name, "ok": c.ok, "expected": c.expected, "observed": c.observed, "note": c.note,
                                   "known_gap": c.known_gap} for c in r.checks],
                       "observed_detail": r.observed, "golden": r.golden, "extras": {k: v for k, v in r.extras.items() if k != "recompute"},
                       "reproducible": (r.extras.get("recompute") or {}).get("reproducible"),
                       "stored_equals_recomputed": next((c.ok for c in r.checks if c.name == "stored_equals_recomputed_engine"), None)})
    payload = {"label": "Synthetic data. Evaluation of the frozen deterministic engines and of the pipeline plumbing; replay fixtures are "
                        "hand-authored, so no model behaviour is measured.",
               "synthetic": True, "specs": detail}
    (directory / "results.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8", newline="\n")
    with (directory / "results.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=CSV_COLUMNS, lineterminator="\n")
        w.writeheader()
        for row in rows:
            w.writerow({**row, "pass": str(row["pass"]).lower(), "synthetic": "true"})
