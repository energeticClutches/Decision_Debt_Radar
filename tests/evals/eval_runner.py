"""The Day-7 evaluation runner (docs/day-7-implementation-brief.md section 2).

Every spec in tests/evals/scenarios/*.yaml is SYNTHETIC (`synthetic: true`) and is run on a rolled-back transaction: it starts from a seeded
decision (or creates a new one through the API), applies declarative `mutations` through the REAL API (the application in-process, the
product routes), and then compares what was stored with what the spec expects.

Rules (brief sections 0 and 2):
  * mutations go through the API (services); never raw SQL on a product table. The two documented exceptions are test-only: the Day-5 E3
    injected insight row, and the approval-bypass ATTEMPT (a statement the database must refuse, run in a savepoint that is rolled back);
  * no band is chosen in advance (D7-01): `band: golden` compares the stored result with the recomputed frozen engine AND with the snapshot
    tests/evals/golden/observed.json, which only `scripts/eval_snapshot.py --write` produces;
  * the LLM is never live: clients are the recorded replay clients, scripted outputs or none. Every model-behaviour measurement is
    reported as NOT EVIDENCED elsewhere (docs/evaluation-report.md).
"""

