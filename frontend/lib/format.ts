// Display formatting only. Nothing here computes a score or a decision.

import type { LifecycleStage, Role } from "./types";

export const STAGES: readonly LifecycleStage[] = ["created", "evidence_gathered", "assessed", "challenged", "validated", "decided"];
export const REPLAY_NOTICE = "Replayed demo fixture, not live model output";

export function stageIndex(stage: LifecycleStage): number {
  return STAGES.indexOf(stage);
}

export function titleCase(value: string | null | undefined): string {
  if (!value) return "";
  return value.replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase());
}

export function fmtDate(value: string | null | undefined): string {
  if (!value) return "";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return d.toISOString().slice(0, 10);
}

export function fmtDateTime(value: string | null | undefined): string {
  if (!value) return "";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return `${d.toISOString().slice(0, 10)} ${d.toISOString().slice(11, 16)} UTC`;
}

export function fmtNumber(value: number | null | undefined, digits = 2): string {
  if (value === null || value === undefined || Number.isNaN(value)) return "n/a";
  return value.toLocaleString("en-US", { maximumFractionDigits: digits, minimumFractionDigits: 0 });
}

export function fmtPercent(value: number | null | undefined, digits = 1): string {
  if (value === null || value === undefined || Number.isNaN(value)) return "n/a";
  return `${(value * 100).toFixed(digits)}%`;
}

/** A value of an input or a detail, shown as the server stored it. */
export function fmtValue(value: unknown): string {
  if (value === null || value === undefined) return "n/a";
  if (typeof value === "number") return fmtNumber(value, 4);
  if (typeof value === "boolean") return value ? "yes" : "no";
  if (typeof value === "string") return value;
  return JSON.stringify(value);
}

export function isReplayProvenance(provenance: string | null | undefined): boolean {
  return !!provenance && provenance !== "live_model_output";
}

export function roleName(role: Role | string): string {
  const names: Record<string, string> = {
    pm: "Product Manager", ba: "Business Analyst", product_analyst: "Product Analyst", bizops: "Strategy and Business Operations",
    dept_leader: "Department Leader", executive: "Executive",
  };
  return names[role] ?? titleCase(role);
}

